// ============================================================
// Interface lifecycle benchmarks (the cold paths).
//
// The dispatch hot path (direct / cached / resolve-per-call) is measured in
// interface_dispatch_bench.cpp; this file covers everything around it:
//   BM_Interface_ValidateManifest      — structural manifest validation
//   BM_Interface_ModuleRegister        — register + unregister one module
//   BM_Interface_ModuleFindFirst       — look an interface up in a registry
//   BM_Interface_BindInterface         — acquire a lease + resolve adapters
//   BM_Interface_ProxyBind             — bind an InterfaceProxy handle
//   BM_Interface_ProxyCall             — one call through a bound proxy
//   BM_Interface_LeaseAcquireRelease   — the lease refcount round-trip
//
// These are setup / discovery costs, not per-call overhead: they explain what
// a consumer pays once when a module is loaded and an interface is bound.
// ============================================================
#include <benchmark/benchmark.h>

#include <cstddef>
#include <cstdint>

#include "ABIX/Interface/Lease.h"
#include "ABIX/Interface/Module.h"
#include "ABIX/Interface/ModuleRegistry.h"
#include "ABIX/Interface/Proxy.h"
#include "ABIX/Interface/Registry.h"

namespace bench_interface_lifecycle {

using skl::abix::model::TypeId;
using skl::abix::poly::abix_manifest_version;
using skl::abix::poly::acquire_lease;
using skl::abix::poly::activate_module;
using skl::abix::poly::bind_interface;
using skl::abix::poly::interface_entry;
using skl::abix::poly::InterfaceId;
using skl::abix::poly::InterfaceManifestEntry;
using skl::abix::poly::InterfaceMethod;
using skl::abix::poly::InterfaceMethodHash;
using skl::abix::poly::InterfaceRegistry;
using skl::abix::poly::ManifestStatus;
using skl::abix::poly::ModuleControl;
using skl::abix::poly::ModuleManifest;
using skl::abix::poly::ModuleRegistry;
using skl::abix::poly::ModuleStatus;
using skl::abix::poly::validate_manifest;

constexpr size_t kSlots = 4;
constexpr size_t kInterfaces = 4;

struct Adder {
    int base;
};

using AddFn = int (*)(const void *, int);

int adder_add(const void *self, int value) { return static_cast<const Adder *>(self)->base + value; }

constexpr TypeId adder_id{0x51, 0x52};
constexpr InterfaceId iid0{0x61, 0x01};
constexpr InterfaceId iid1{0x61, 0x02};
constexpr InterfaceId iid2{0x61, 0x03};
constexpr InterfaceId iid3{0x61, 0x04};

// One object, one method table shared by every interface entry, and a manifest
// that advertises kInterfaces x kSlots bindings.
struct Fixture {
    Adder object{1};
    InterfaceMethod methods[kSlots];
    InterfaceManifestEntry entries[kInterfaces];
    ModuleManifest manifest;
    InterfaceRegistry<8> bind_registry;

    Fixture() {
        for (size_t i = 0; i < kSlots; ++i)
            methods[i] = {InterfaceMethodHash{}, interface_entry(&adder_add), static_cast<uint32_t>(i), 0};
        const InterfaceId ids[kInterfaces] = {iid0, iid1, iid2, iid3};
        for (size_t i = 0; i < kInterfaces; ++i)
            entries[i] = {ids[i], 1, 0, methods, static_cast<uint32_t>(kSlots), 0};
        manifest = {abix_manifest_version, 1, 0, static_cast<uint32_t>(kInterfaces), entries, 0, 0, nullptr};
        (void)bind_registry.add({iid0, adder_id, methods, static_cast<uint32_t>(kSlots), 1, 0});
    }
};

Fixture &fixture() {
    static Fixture instance;
    return instance;
}

// The per-interface proxy class a consumer writes by hand (generated by AMC in
// practice): the shared machinery lives in InterfaceProxy, the class adds only
// its typed methods.
struct ProxyTraits {
    static constexpr InterfaceId id = iid0;
    static constexpr uint32_t version = 1;
    static constexpr size_t slots = kSlots;
};

class TestProxy : public skl::abix::poly::InterfaceProxy<ProxyTraits> {
    using Base = skl::abix::poly::InterfaceProxy<ProxyTraits>;

public:
    using Base::Base;
    int add(int value) const noexcept { return this->template call<AddFn>(0, value); }
};

void BM_Interface_ValidateManifest(benchmark::State &state) {
    Fixture &f = fixture();
    for (auto _ : state) {
        ManifestStatus status = validate_manifest(&f.manifest);
        benchmark::DoNotOptimize(status);
    }
}
BENCHMARK(BM_Interface_ValidateManifest);

void BM_Interface_ModuleRegister(benchmark::State &state) {
    Fixture &f = fixture();
    ModuleRegistry<8, 32> registry;
    for (auto _ : state) {
        ModuleControl control;
        ModuleStatus added = registry.register_module(control, f.manifest);
        benchmark::DoNotOptimize(added);
        ModuleStatus removed = registry.unregister_module(control.id);
        benchmark::DoNotOptimize(removed);
    }
}
BENCHMARK(BM_Interface_ModuleRegister);

void BM_Interface_ModuleFindFirst(benchmark::State &state) {
    Fixture &f = fixture();
    ModuleRegistry<8, 32> registry;
    ModuleControl control;
    (void)registry.register_module(control, f.manifest);
    for (auto _ : state) {
        const auto *found = registry.find_first(iid0);
        benchmark::DoNotOptimize(found);
    }
}
BENCHMARK(BM_Interface_ModuleFindFirst);

void BM_Interface_BindInterface(benchmark::State &state) {
    Fixture &f = fixture();
    ModuleRegistry<8, 32> registry;
    ModuleControl control;
    (void)registry.register_module(control, f.manifest);
    const auto *binding = registry.find_first(iid0);
    for (auto _ : state) {
        auto bound = bind_interface<kSlots>(*binding, &f.object);
        bool valid = bound.valid();
        benchmark::DoNotOptimize(valid);
    }
}
BENCHMARK(BM_Interface_BindInterface);

void BM_Interface_ProxyBind(benchmark::State &state) {
    Fixture &f = fixture();
    for (auto _ : state) {
        TestProxy proxy(f.bind_registry, &f.object, adder_id, 1);
        bool valid = proxy.valid();
        benchmark::DoNotOptimize(valid);
    }
}
BENCHMARK(BM_Interface_ProxyBind);

void BM_Interface_ProxyCall(benchmark::State &state) {
    Fixture &f = fixture();
    TestProxy proxy(f.bind_registry, &f.object, adder_id, 1);
    for (auto _ : state) {
        int result = proxy.add(41);
        benchmark::DoNotOptimize(result);
    }
}
BENCHMARK(BM_Interface_ProxyCall);

void BM_Interface_LeaseAcquireRelease(benchmark::State &state) {
    ModuleControl control;
    (void)activate_module(control);
    for (auto _ : state) {
        auto lease = acquire_lease(control);
        bool valid = lease.valid();
        benchmark::DoNotOptimize(valid);
        lease.release();
    }
}
BENCHMARK(BM_Interface_LeaseAcquireRelease);

}   // namespace bench_interface_lifecycle
