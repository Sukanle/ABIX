std::string hash_literal(Hash128 value) {
    std::ostringstream out;
    out << "0x" << std::hex << std::setfill('0') << std::setw(16) << value.hi << std::setw(16) << value.lo;
    return out.str();
}

// A 128-bit identity as two 64-bit C literal halves (a single 128-bit integer
// literal does not exist in C++).
std::string id_literal(Hash128 value) {
    std::ostringstream out;
    out
        << "{0x"
        << std::hex
        << std::setfill('0')
        << std::setw(16)
        << value.lo
        << "ULL, 0x"
        << std::setw(16)
        << value.hi
        << "ULL}";
    return out.str();
}

std::string cpp_string(const std::string &value) {
    std::string result = "\"";
    for (const char c : value) {
        if (c == '\\' || c == '"') result += '\\';
        result += c;
    }
    return result + '"';
}

using TypeKey = std::pair<uint64_t, uint64_t>;
using TypeMap = std::map<TypeKey, const Type *>;

TypeMap index_types(const AbiModule &module) {
    TypeMap map;
    for (const auto &type : module.types)
        map[{type.id.lo, type.id.hi}] = &type;
    return map;
}

const Field *field_at(const AbiModule &module, uint32_t index) {
    return index < module.fields.size() ? &module.fields[index] : nullptr;
}

std::string field_label(const AbiModule &module, uint32_t index) {
    const Field *field = field_at(module, index);
    return field != nullptr ? field->name : std::string("<default>");
}

// Byte width of a field's ABI type, resolved through the module's type index.
uint32_t field_type_size(const AbiModule &module, const TypeMap &types, uint32_t field_index) {
    const Field *field = field_at(module, field_index);
    if (field == nullptr) return 0;
    const auto it = types.find({field->type_id.lo, field->type_id.hi});
    return it != types.end() ? it->second->size : 0;
}

std::string int_type(uint32_t size) {
    switch (size) {
        case 1:  return "std::int8_t";
        case 2:  return "std::int16_t";
        case 4:  return "std::int32_t";
        case 8:  return "std::int64_t";
        default: return {};
    }
}

std::string float_type(uint32_t size) {
    switch (size) {
        case 4:  return "float";
        case 8:  return "double";
        default: return {};
    }
}

